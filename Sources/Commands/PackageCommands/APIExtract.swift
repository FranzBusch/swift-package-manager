import ArgumentParser
import Basics
import CoreCommands
import PackageGraph
import PackageModel
import SPMBuildCore

import struct TSCBasic.StringError

extension SwiftPackageCommand.API {
    struct ExperimentalExtract: AsyncSwiftCommand {
        static let configuration = CommandConfiguration(
            commandName: "experimental-extract",
            abstract: "Extract the public API of a package's Swift modules.",
            discussion: """
            You can use the `experimental-extract` command to write out the public API surface of \
            the Swift modules in a package, as `.swiftinterface` text, to standard output. This is \
            useful for reviewing an API, for attaching an API surface to a pull request, or for \
            committing the API surface to a repository so that changes to it appear as a reviewable \
            diff.

            By default, every Swift module that is part of a library product is extracted. The \
            `--products` and `--targets` options may be used to restrict the scope. Each module is \
            preceded by a `// MARK: -` banner naming it.

            The emitted interface is generated by the Swift compiler, so its exact formatting is \
            determined by the toolchain in use rather than by the package manager. The leading \
            metadata comments are omitted so that the output is stable across toolchains, hosts, \
            and build configurations.

            The package is built with library evolution enabled so that the extracted API is the \
            resilient form that clients program against, rather than one containing compiler \
            implementation details. This means the build performed by this command is separate \
            from an ordinary `swift build`, and that extraction can fail for packages that cannot \
            be built with library evolution.
            """,
            helpNames: [.short, .long, .customLong("help", withSingleDash: true)]
        )

        @OptionGroup(visibility: .hidden)
        var globalOptions: GlobalOptions

        @Option(
            parsing: .upToNextOption,
            help: "One or more products to include in the extracted API. If present, only the specified products (and any targets specified using `--targets`) will be extracted."
        )
        var products: [String] = []

        @Option(
            parsing: .upToNextOption,
            help: "One or more targets to include in the extracted API. If present, only the specified targets (and any products specified using `--products`) will be extracted."
        )
        var targets: [String] = []

        func run(_ swiftCommandState: SwiftCommandState) async throws {
            // Extraction relies on the build system reporting where it wrote the module
            // interfaces, which is currently only wired up for the default build system.
            let buildSystemKind = swiftCommandState.options.build.buildSystem
            guard buildSystemKind == .swiftbuild else {
                throw StringError(
                    "'swift package api experimental-extract' requires the default build system; '--build-system \(buildSystemKind.rawValue)' is not supported"
                )
            }

            let packageGraph = try await swiftCommandState.loadPackageGraph()
            let modules = try packageGraph.selectAPIModules(
                products: self.products,
                targets: self.targets,
                observabilityScope: swiftCommandState.observabilityScope,
                diagnoseMissingNames: true
            )

            guard !modules.isEmpty else {
                swiftCommandState.observabilityScope.emit(
                    error: "no Swift library modules found to extract; use --targets to select specific targets"
                )
                throw ExitCode.failure
            }

            // Ask the compiler for `.swiftinterface` files alongside the `.swiftmodule`s. The
            // build manifest depends on these flags, so it must not be cached.
            var productsBuildParameters = try swiftCommandState.productsBuildParameters
            productsBuildParameters.driverParameters.enableParseableModuleInterfaces = true

            // Extract the resilient form of the API. Without library evolution the compiler emits
            // implementation details that are not the API a client programs against — stored
            // properties carry `@_hasInitialValue`, and synthesized conformances appear under
            // internal names such as `__derived_enum_equals` rather than as `==`. It also warns
            // that module interfaces require library evolution.
            productsBuildParameters.flags.swiftCompilerFlags.append(
                BuildFlag(value: "-enable-library-evolution", source: .commandLineOptions)
            )

            // Print types the way the package author wrote them, rather than resolved and fully
            // qualified. Without these the interface refers to `Swift::Int` instead of `Int`, and
            // replaces a typealias with the type it resolves to. Module selectors exist to keep an
            // interface unambiguous when it is recompiled, which does not apply here because this
            // output is for people to read and is never fed back to the compiler.
            for flag in [
                "-Xfrontend", "-module-interface-preserve-types-as-written",
                "-Xfrontend", "-disable-module-selectors-in-module-interface",
            ] {
                productsBuildParameters.flags.swiftCompilerFlags.append(
                    BuildFlag(value: flag, source: .commandLineOptions)
                )
            }

            let buildSystem = try await swiftCommandState.createBuildSystem(
                cacheBuildManifest: false,
                productsBuildParameters: productsBuildParameters
            )
            try await buildSystem.build(subset: .allExcludingTests, buildOutputs: [])

            let productsPath = try await buildSystem.buildProductsPath(for: productsBuildParameters)
            let fileSystem = swiftCommandState.fileSystem

            // Read every interface up front so that a missing one fails before we have written any
            // partial output.
            var interfaces: [(module: String, contents: String)] = []
            for module in modules.sorted() {
                let path = try Self.locateModuleInterface(
                    module: module,
                    productsPath: productsPath,
                    fileSystem: fileSystem
                )
                var contents: String = try fileSystem.readFileContents(path)
                contents = Self.strippingMetadataComments(from: contents)
                interfaces.append((module, contents))
            }

            for interface in interfaces {
                print("// MARK: - \(interface.module)")
                print(interface.contents)
            }
        }

        /// Find the public `.swiftinterface` that the build system emitted for a module.
        ///
        /// Swift Build writes interfaces into a `<Module>.swiftmodule` directory, named after the
        /// module triple, alongside the private and package interfaces. Rather than reconstructing
        /// that triple, search the directory and pick the public interface.
        private static func locateModuleInterface(
            module: String,
            productsPath: Basics.AbsolutePath,
            fileSystem: any FileSystem
        ) throws -> Basics.AbsolutePath {
            // A flat `<Module>.swiftinterface` next to the products, as emitted by some layouts.
            let flatPath = productsPath.appending("\(module).swiftinterface")
            if fileSystem.exists(flatPath) {
                return flatPath
            }

            let moduleDirectory = productsPath.appending("\(module).swiftmodule")
            guard fileSystem.isDirectory(moduleDirectory) else {
                throw StringError(
                    "could not find a module interface for '\(module)' at '\(moduleDirectory.pathString)'"
                )
            }

            let candidates = try fileSystem.getDirectoryContents(moduleDirectory)
                .filter { $0.hasSuffix(".swiftinterface") }
                // Exclude the private and package interfaces; only the public API is extracted.
                .filter { !$0.hasSuffix(".private.swiftinterface") && !$0.hasSuffix(".package.swiftinterface") }
                .sorted()

            guard let candidate = candidates.first else {
                throw StringError(
                    "could not find a module interface for '\(module)' in '\(moduleDirectory.pathString)'"
                )
            }
            return moduleDirectory.appending(candidate)
        }

        /// Drop the leading `// swift-*` metadata comments, which embed the compiler version,
        /// target triple, and build flags. Those change between toolchains, hosts, and build
        /// configurations, so keeping them would add diff noise unrelated to the API whenever an
        /// extracted interface is committed to a repository.
        private static func strippingMetadataComments(from interface: String) -> String {
            var lines = interface.split(separator: "\n", omittingEmptySubsequences: false)
            while let first = lines.first, first.hasPrefix("// swift-") {
                lines.removeFirst()
            }
            return lines.joined(separator: "\n")
        }
    }
}
